const toMerchantDisplayName = (key) => {
  if (!key) return "";
  if (MERCHANT_DISPLAY_NAMES[key]) return MERCHANT_DISPLAY_NAMES[key];
  return key
    .split(" ")
    .map((part) =>
      part.length <= 3 && !part.includes(".")
        ? part.toUpperCase()
        : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join(" ");
};

export const levenshteinDistance = (a, b) => {
  const left = normalize(a);
  const right = normalize(b);
  const matrix = Array(right.length + 1)
    .fill(null)
    .map(() => Array(left.length + 1).fill(null));

  for (let i = 0; i <= left.length; i += 1) matrix[0][i] = i;
  for (let j = 0; j <= right.length; j += 1) matrix[j][0] = j;

  for (let j = 1; j <= right.length; j += 1) {
    for (let i = 1; i <= left.length; i += 1) {
      const indicator = left[i - 1] === right[j - 1] ? 0 : 1;
      matrix[j][i] = Math.min(
        matrix[j][i - 1] + 1,
        matrix[j - 1][i] + 1,
        matrix[j - 1][i - 1] + indicator,
      );
    }
  }

  return matrix[right.length][left.length];
};

export const findMerchant = (text) => {
  const lower = normalize(text);
  if (!lower) return null;

  if (MERCHANT_DATABASE[lower]) {
    return {
      ...MERCHANT_DATABASE[lower],
      confidence: "high",
      matchType: "exact",
      matchedKey: lower,
      merchantName: toMerchantDisplayName(lower),
    };
  }

  for (const [key, value] of Object.entries(MERCHANT_DATABASE)) {
    if (key.length <= 4) {
      const escapedKey = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const regex = new RegExp(`(?:^|\\s|,|\\.|-|/|&)${escapedKey}(?:$|\\s|,|\\.|-|/|&)`, "i");
      if (regex.test(lower)) {
        return {
          ...value,
          confidence: "high",
          matchType: "partial",
          matchedKey: key,
          merchantName: toMerchantDisplayName(key),
        };
      }
    } else {
      if (lower.includes(key) || key.includes(lower)) {
        return {
          ...value,
          confidence: "high",
          matchType: "partial",
          matchedKey: key,
          merchantName: toMerchantDisplayName(key),
        };
      }
    }
  }

  for (const [key, value] of Object.entries(MERCHANT_DATABASE)) {
    const threshold = key.length > 8 ? 3 : 2;
    if (key.length > 3 && levenshteinDistance(lower, key) <= threshold) {
      return {
        ...value,
        confidence: "medium",
        matchType: "fuzzy",
        matchedKey: key,
        merchantName: toMerchantDisplayName(key),
      };
    }
  }

  return null;
};
